"""Build the small, offline sprite catalogue for the Discord PNG renderer.

Run from any directory: python3 scripts/pack-board-art.py (requires Pillow).
Use --source-dir to reuse original PNGs named after the final component of their URLs
in subdirectories wiki/, runelite/, and wise-old-man/. Live Workers never fetch artwork.
"""

import argparse
import base64
from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
import itertools
import json
from pathlib import Path
from urllib.parse import unquote, urlsplit
from urllib.request import Request, urlopen

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = Path(__file__).with_name("board-art-sources.json")
OUTPUT = ROOT / "backend/src/board-art"
SIZE = 44


def pixel_data(image):
    return image.get_flattened_data() if hasattr(image, "get_flattened_data") else list(image.getdata())


def packed_sprite(source):
    with Image.open(BytesIO(source)) as png:
        sprite = png.convert("RGBA")
    bounds = sprite.getchannel("A").getbbox()
    if not bounds:
        raise ValueError("empty image")
    sprite = sprite.crop(bounds)
    if sprite.getchannel("A").getextrema()[0] == 255:
        raise ValueError("expected transparent artwork")
    scale = SIZE / max(sprite.size)
    size = tuple(max(1, round(n * scale)) for n in sprite.size)
    resample = Image.Resampling.NEAREST if scale >= 1 else Image.Resampling.LANCZOS
    sprite = sprite.resize(size, resample)
    pixels = pixel_data(sprite)
    opaque = [pixel[:3] for pixel in pixels if pixel[3] >= 128]
    rgb = Image.new("RGB", (len(opaque), 1))
    rgb.putdata(opaque)
    indexed = rgb.quantize(colors=63, dither=Image.Dither.NONE)
    # Index zero is reserved for transparent pixels. Encode runs of one to four pixels
    # in a single byte: two bits for the length and six for the palette index.
    used_indices = sorted(set(pixel_data(indexed)))
    remap = {old: new for new, old in enumerate(used_indices, start=1)}
    source_palette = indexed.getpalette()
    palette = [value for index in used_indices for value in source_palette[index * 3:index * 3 + 3]]
    colours = iter(pixel_data(indexed))
    indices = (remap[next(colours)] if pixel[3] >= 128 else 0 for pixel in pixels)
    runs = bytearray()
    for index, group in itertools.groupby(indices):
        length = sum(1 for _ in group)
        while length > 0:
            count = min(4, length)
            runs.append((count - 1) << 6 | index)
            length -= count
    return base64.b64encode(bytes([*size, len(used_indices), *palette]) + runs).decode("ascii")


def read_source(url, cache):
    parsed = urlsplit(url)
    provider = "wiki" if parsed.hostname == "oldschool.runescape.wiki" else parsed.path.split("/")[1]
    file = cache / provider / unquote(parsed.path.rsplit("/", 1)[1])
    if file.exists():
        return file.read_bytes()
    request = Request(url, headers={"User-Agent": "BOTW Discord Artwork / https://github.com/marcushill13/botw"})
    with urlopen(request, timeout=25) as response:
        data = response.read()
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_bytes(data)
    return data


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-dir", type=Path, default=ROOT / ".board-art-cache")
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text())
    OUTPUT.mkdir(exist_ok=True)
    for category, sources in manifest.items():
        def build(entry):
            key, url = entry
            try:
                return key, packed_sprite(read_source(url, args.source_dir))
            except Exception as error:
                raise RuntimeError(f"{category}/{key}: {url}: {error}") from error

        with ThreadPoolExecutor(6) as pool:
            entries = list(pool.map(build, sources.items()))
        module = "// Generated by scripts/pack-board-art.py. Sources: scripts/board-art-sources.json.\n"
        module += "export default {\n"
        module += ",\n".join(f"\t{json.dumps(key)}: {json.dumps(sprite)}" for key, sprite in entries)
        module += "\n};\n"
        (OUTPUT / (category + ".js")).write_text(module)


if __name__ == "__main__":
    main()
