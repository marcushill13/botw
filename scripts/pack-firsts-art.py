"""Pack actual RuneLite item sprites for preset first prizes; Workers render them offline."""
import sys
sys.dont_write_bytecode = True
from concurrent.futures import ThreadPoolExecutor
import importlib.util
import json
from pathlib import Path
import re
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('art', ROOT / 'scripts/pack-board-art.py')
art = importlib.util.module_from_spec(spec)
spec.loader.exec_module(art)
ids = set()
def walk(value):
    if isinstance(value, dict):
        item = value.get('itemId')
        if isinstance(item, int) and item > 0:
            ids.add(item)
        for child in value.values(): walk(child)
    elif isinstance(value, list):
        for child in value: walk(child)
walk(json.loads((ROOT / 'src/main/resources/com/botw/boss-drops.json').read_text()))
rewards = (ROOT / 'src/main/java/com/botw/data/WeeklyRewards.java').read_text()
ids.update(map(int, re.findall(r'Map.entry\("[^"]+", (\d+)\)', rewards)))
constants = {'WINT_TORCH': 20720, 'PHOENIXPET': 20693, 'PYROMANCER_BOOTS': 20710,
             'PYROMANCER_TOP': 20704, 'PYROMANCER_HOOD': 20708, 'PYROMANCER_BOTTOM': 20706,
             'TOME_OF_FIRE_UNCHARGED': 20716, 'PYROMANCER_GLOVES': 20712}
ids.update(constants[name] for name in re.findall(r'Map.entry\("[^"]+", ItemID\.(\w+)\)', rewards))
cache = ROOT / '.board-art-cache/items'
cache.mkdir(parents=True, exist_ok=True)
def pack(item):
    file = cache / f'{item}.png'
    if not file.exists():
        file.write_bytes(urlopen(f'https://static.runelite.net/cache/item/icon/{item}.png', timeout=30).read())
    return str(item), art.packed_sprite(file.read_bytes())
with ThreadPoolExecutor(max_workers=12) as pool:
    sprites = dict(pool.map(pack, sorted(ids)))
(ROOT / 'backend/src/board-art/items.js').write_text(
    '// Actual OSRS item sprites from static.runelite.net; artwork copyright Jagex.\n'
    '// Generated by scripts/pack-firsts-art.py.\nexport default ' + json.dumps(sprites, separators=(',', ':')) + ';\n')
print(f'Packed {len(sprites)} item sprites')
